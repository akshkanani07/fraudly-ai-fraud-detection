/* ============================================================
 * Content — with Glassmorphism
 * ============================================================ */
function DropdownMenuContent({
  className,
  sideOffset = 6,
  align = "start",
  ...props
}: React.ComponentProps<typeof MenuPrimitive.Popup> & {
  sideOffset?: number;
  align?: "start" | "center" | "end";
}) {
  return (
    <MenuPrimitive.Portal>
      <MenuPrimitive.Positioner
        sideOffset={sideOffset}
        align={align}
        className="z-50"
      >
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            /* Base Layout */
            "z-50 min-w-[10rem] overflow-hidden rounded-xl border p-1 shadow-2xl outline-hidden",
            /* ✅ Glassmorphism — Blur + Semi-Transparent */
            "border-border/60 bg-popover/80 backdrop-blur-2xl backdrop-saturate-150",
            "text-popover-foreground",
            /* Subtle Ring for Depth */
            "ring-1 ring-white/5 dark:ring-white/10",
            /* Animation */
            "data-[state=open]:animate-in data-[state=closed]:animate-out",
            "data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0",
            "data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95",
            "data-[side=bottom]:slide-in-from-top-2",
            "data-[side=left]:slide-in-from-right-2",
            "data-[side=right]:slide-in-from-left-2",
            "data-[side=top]:slide-in-from-bottom-2",
            className,
          )}
          {...props}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  );
}

